#!/usr/bin/env node
// Writes the route words browser telemetry may report verbatim (shell-front's
// src/telemetryRoutes.ts). Any other path segment — an id, a slug, a private
// name — is reported as `:id`, so this list is what keeps operations such as
// `/api/projects/:id/archive` and `/api/projects/:id/restore` apart on the
// dashboards. A word missing here only coarsens a dashboard row; it never leaks.
//
// Sources: string-literal Express routes in the backends and <Route path> in
// the fronts. Run after adding a route:  npm run telemetry:routes
// `--check` exits 1 when the committed file is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
// Every front that initializes telemetry itself: the shell (and its remotes) and sign-in.
const OUTS = ['shell-front', 'auth-front'].map((app) => join(ROOT, `apps/frontend/${app}/src/telemetryRoutes.ts`));
const SOURCES = [
  // A template literal with `${` never matches: its words are not knowable here.
  {
    dir: 'apps/backend',
    ext: /\.ts$/,
    pattern: /\.(?:get|post|put|patch|delete|use|all|route)\(\s*['"`](\/[^'"`$]*)['"`]/g
  },
  { dir: 'apps/frontend', ext: /\.tsx$/, pattern: /<Route\b[^>]*?\bpath=["']([^"']+)["']/g }
];
const WORD = /^[a-z][a-z0-9-]{0,39}$/;
const SKIP_DIRS = new Set(['node_modules', 'dist', 'coverage', '__tests__', 'e2e']);

function* files(dir, ext) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name) || entry.name.startsWith('.')) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(path, ext);
    else if (ext.test(entry.name) && !/\.(?:test|spec)\./.test(entry.name)) yield path;
  }
}

const words = new Set();
for (const { dir, ext, pattern } of SOURCES) {
  for (const file of files(join(ROOT, dir), ext)) {
    for (const [, route] of readFileSync(file, 'utf8').matchAll(pattern)) {
      for (const segment of route.split('/')) if (WORD.test(segment)) words.add(segment);
    }
  }
}

const body = [...words]
  .sort()
  .map((word) => `  '${word}'`)
  .join(',\n');
const content = `// Generated by scripts/telemetry-routes.mjs from the backends' and fronts' route
// definitions; run \`npm run telemetry:routes\` after adding a route. Browser telemetry
// reports these words verbatim and every other path segment as \`:id\`.
export const TELEMETRY_ROUTE_SEGMENTS: readonly string[] = [
${body}
];
`;

const read = (file) => {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return ''; // missing counts as stale
  }
};

if (process.argv.includes('--check')) {
  const stale = OUTS.filter((file) => read(file) !== content);
  if (stale.length) {
    console.error(
      `Out of date: ${stale.map((file) => file.slice(ROOT.length)).join(', ')}. Run \`npm run telemetry:routes\`.`
    );
    process.exit(1);
  }
} else {
  for (const file of OUTS) writeFileSync(file, content);
  console.log(`Wrote ${words.size} route words to ${OUTS.map((file) => file.slice(ROOT.length)).join(', ')}`);
}
